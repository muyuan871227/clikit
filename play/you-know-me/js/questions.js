// Build shuffled deck for a given level
export function buildDeck(level, includeSpecial = true) {
  let questions;
  switch (level) {
    case 1: questions = [...level1Questions]; break;
    case 2: questions = [...level2Questions]; break;
    case 3: questions = [...level3Questions]; break;
    default: questions = [...level1Questions];
  }

  const deck = questions.map(q => ({
    text: q,
    level,
    type: 'normal',
    source: 'static'
  }));

  // Mix in special cards at 15% weight
  if (includeSpecial) {
    const specialCount = Math.ceil(deck.length * 0.15);
    const allSpecial = [
      ...specialCards.secret.map(q => ({ text: q, level, type: 'secret', source: 'static' })),
      ...specialCards.memory.map(q => ({ text: q, level, type: 'memory', source: 'static' })),
      ...specialCards.courage.map(q => ({ text: q, level, type: 'courage', source: 'static' }))
    ];
    // Shuffle special cards and take some
    shuffleArray(allSpecial);
    deck.push(...allSpecial.slice(0, specialCount));
  }

  shuffleArray(deck);
  return deck;
}

// Fisher-Yates shuffle
export function shuffleArray(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}
